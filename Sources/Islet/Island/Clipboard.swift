import AppKit
import SwiftUI

/// What was copied recently: text, links, images and files, newest first. Kept in memory
/// only (nothing is written to disk), and copies that password managers mark as concealed
/// or transient are never recorded.
@MainActor
@Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    struct Entry: Identifiable, Equatable {
        enum Content: Equatable {
            case text(String)
            case link(URL)
            case image(NSImage)
            case files([URL])
        }

        let id = UUID()
        let content: Content
        let date: Date
        let sourceApp: String?

        static func == (a: Entry, b: Entry) -> Bool { a.id == b.id }
    }

    private(set) var entries: [Entry] = []
    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private let limit = 30

    var isEnabled = false {
        didSet {
            guard isEnabled != oldValue else { return }
            if isEnabled { start() } else { stop() }
        }
    }

    private func start() {
        changeCount = NSPasteboard.general.changeCount
        // The pasteboard has no change notification; its counter is cheap to read.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
        entries = []
    }

    func clear() { entries = [] }

    func remove(_ entry: Entry) { entries.removeAll { $0.id == entry.id } }

    /// Puts an entry back on the clipboard (and at the top of the list).
    func copy(_ entry: Entry) {
        let board = NSPasteboard.general
        board.clearContents()
        switch entry.content {
        case .text(let text): board.setString(text, forType: .string)
        case .link(let url): board.writeObjects([url as NSURL])
        case .image(let image): board.writeObjects([image])
        case .files(let urls): board.writeObjects(urls.map { $0 as NSURL })
        }
        changeCount = board.changeCount
        entries.removeAll { $0.id == entry.id }
        entries.insert(Entry(content: entry.content, date: Date(), sourceApp: entry.sourceApp), at: 0)
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let types = Set(board.types ?? [])
        // nspasteboard.org conventions: passwords and one-off data aren't history.
        let private_ = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        guard !types.contains(where: { private_.contains($0.rawValue) }) else { return }
        guard let content = Self.read(board) else { return }
        // The same thing copied again moves up instead of repeating.
        entries.removeAll { $0.content == content }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        entries.insert(Entry(content: content, date: Date(), sourceApp: app), at: 0)
        if entries.count > limit { entries.removeLast(entries.count - limit) }
    }

    private static func read(_ board: NSPasteboard) -> Entry.Content? {
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        if let text = board.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
            if let url = URL(string: text), let scheme = url.scheme, ["http", "https"].contains(scheme), !text.contains(" ") {
                return .link(url)
            }
            return .text(String(text.prefix(5000)))
        }
        if let image = NSImage(pasteboard: board) { return .image(image) }
        return nil
    }
}

/// The shelf's Clipboard tab: recent copies as a row of cards; clicking one copies it again.
struct ClipboardView: View {
    let history: ClipboardHistory
    @State private var copied: UUID?

    var body: some View {
        if history.entries.isEmpty {
            RoundedRectangle(cornerRadius: 14, style: .continuous)
                .strokeBorder(.white.opacity(0.35), style: StrokeStyle(lineWidth: 1.5, dash: [6, 5]))
                .background(RoundedRectangle(cornerRadius: 14, style: .continuous).fill(.white.opacity(0.04)))
                .overlay {
                    Label("Things you copy show up here", systemImage: "doc.on.clipboard")
                        .font(.system(size: 12, weight: .medium))
                        .foregroundStyle(.white.opacity(0.65))
                }
        } else {
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: 8) {
                    ForEach(history.entries) { entry in
                        ClipboardCard(entry: entry, copied: copied == entry.id,
                                      copy: {
                                          history.copy(entry)
                                          withAnimation(IslandMotion.quick) { copied = history.entries.first?.id }
                                      },
                                      remove: { history.remove(entry) })
                    }
                }
            }
            .animation(IslandMotion.subtle, value: history.entries)
        }
    }
}

private struct ClipboardCard: View {
    let entry: ClipboardHistory.Entry
    let copied: Bool
    let copy: () -> Void
    let remove: () -> Void
    @State private var hovering = false

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            preview
                .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
            HStack(spacing: 4) {
                Image(systemName: copied ? "checkmark" : symbol)
                    .foregroundStyle(copied ? Color.green : .white.opacity(0.5))
                Text(copied ? "Copied" : entry.sourceApp ?? entry.date.formatted(.relative(presentation: .named)))
                    .lineLimit(1)
            }
            .font(.system(size: 9, weight: .medium))
            .foregroundStyle(.white.opacity(0.5))
        }
        .padding(8)
        .frame(width: 118, height: 76)
        .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(.white.opacity(hovering ? 0.16 : 0.09)))
        .contentShape(Rectangle())
        .routedClick("clip.\(entry.id)", action: copy)
        .onTapGesture(perform: copy)
        .overlay(alignment: .topTrailing) {
            if hovering {
                Image(systemName: "xmark.circle.fill")
                    .font(.system(size: 13))
                    .foregroundStyle(.white, .black.opacity(0.6))
                    .padding(3)
                    .routedClick("clip.remove.\(entry.id)", action: remove)
                    .onTapGesture(perform: remove)
            }
        }
        .onHover { hovering = $0 }
        .onDrag { provider }
        .help("Click to copy again")
    }

    @ViewBuilder
    private var preview: some View {
        switch entry.content {
        case .text(let text):
            Text(text)
                .font(.system(size: 10.5))
                .foregroundStyle(.white.opacity(0.9))
                .lineLimit(4)
        case .link(let url):
            VStack(alignment: .leading, spacing: 2) {
                Text(url.host() ?? url.absoluteString)
                    .font(.system(size: 11, weight: .semibold))
                    .foregroundStyle(.white)
                Text(url.absoluteString)
                    .font(.system(size: 9.5))
                    .foregroundStyle(.blue.opacity(0.9))
                    .lineLimit(2)
            }
        case .image(let image):
            Image(nsImage: image)
                .resizable()
                .aspectRatio(contentMode: .fit)
                .clipShape(.rect(cornerRadius: 6))
        case .files(let urls):
            HStack(spacing: 6) {
                Image(nsImage: NSWorkspace.shared.icon(forFile: urls[0].path))
                    .resizable()
                    .frame(width: 30, height: 30)
                Text(urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) files")
                    .font(.system(size: 10.5, weight: .medium))
                    .foregroundStyle(.white.opacity(0.9))
                    .lineLimit(3)
            }
        }
    }

    private var symbol: String {
        switch entry.content {
        case .text: "text.alignleft"
        case .link: "link"
        case .image: "photo"
        case .files: "doc"
        }
    }

    private var provider: NSItemProvider {
        switch entry.content {
        case .text(let text): NSItemProvider(object: text as NSString)
        case .link(let url): NSItemProvider(object: url as NSURL)
        case .image(let image): NSItemProvider(object: image)
        case .files(let urls): NSItemProvider(contentsOf: urls[0]) ?? NSItemProvider()
        }
    }
}
